"""Generate src/components/hero-art.tsx: a line-art football over pitch markings.

The ball is a truncated icosahedron (12 pentagons, 20 hexagons) projected onto a sphere with
curved seams, lit from the upper left. Pure Python, no dependencies:
    python3 studio/scripts/hero-art.py > studio/src/components/hero-art.tsx
"""

import math
import os
from itertools import product

PHI = (1 + 5**0.5) / 2
CX, CY, R = 330.0, 205.0, 148.0
STEPS = 8  # points per seam, so seams curve with the sphere
LIGHT = (-0.45, 0.55, 0.70)


def norm(v):
    n = math.sqrt(sum(c * c for c in v))
    return tuple(c / n for c in v)


def cyclic(p):
    x, y, z = p
    return [(x, y, z), (z, x, y), (y, z, x)]


def signed(p):
    out = set()
    for signs in product((1, -1), repeat=3):
        out.add(tuple(s * c if c else 0.0 for s, c in zip(signs, p, strict=True)))
    return out


def points(*bases):
    pts = set()
    for b in bases:
        for c in cyclic(b):
            pts |= signed(c)
    return [norm(p) for p in pts]


VERTS = points((0, 1, 3 * PHI), (1, 2 + PHI, 2 * PHI), (PHI, 2, 2 * PHI + 1))
PENTS = points((0, 1, PHI))
HEXES = points((1, 1, 1), (0, 1 / PHI, PHI))
assert len(VERTS) == 60 and len(PENTS) == 12 and len(HEXES) == 20


def dot(a, b):
    return sum(x * y for x, y in zip(a, b, strict=True))


def cross(a, b):
    return (a[1] * b[2] - a[2] * b[1], a[2] * b[0] - a[0] * b[2], a[0] * b[1] - a[1] * b[0])


def face(centre, k):
    near = sorted(VERTS, key=lambda v: -dot(v, centre))[:k]
    u = norm(cross(centre, (0.3, 0.5, 0.8)))
    w = cross(centre, u)
    return sorted(near, key=lambda v: math.atan2(dot(v, w), dot(v, u)))


def rotate(v, ax, ay, az):
    x, y, z = v
    y, z = y * math.cos(ax) - z * math.sin(ax), y * math.sin(ax) + z * math.cos(ax)
    x, z = x * math.cos(ay) + z * math.sin(ay), -x * math.sin(ay) + z * math.cos(ay)
    x, y = x * math.cos(az) - y * math.sin(az), x * math.sin(az) + y * math.cos(az)
    return (x, y, z)


# Rotation (x, y, z, radians); HERO_ANGLES="x,y,z" tries another view of the ball.
ANGLES = tuple(float(a) for a in os.environ.get("HERO_ANGLES", "0.7,-0.5,0.5").split(","))


def project(v):
    return (CX + R * v[0], CY - R * v[1])


def rim(a, b):
    """Points along the outline from a to b (both on z = 0), the short way round."""
    t0, t1 = math.atan2(a[1], a[0]), math.atan2(b[1], b[0])
    d = (t1 - t0 + math.pi) % (2 * math.pi) - math.pi
    n = max(2, int(abs(d) / 0.05))
    return [(math.cos(t0 + d * i / n), math.sin(t0 + d * i / n), 0.0) for i in range(1, n)]


def outline(corners):
    """The panel's curved outline, clipped to the visible half of the ball."""
    dense = []
    for a, b in zip(corners, corners[1:] + corners[:1], strict=True):
        for i in range(STEPS):
            t = i / STEPS
            dense.append(norm(tuple(p + (q - p) * t for p, q in zip(a, b, strict=True))))
    start = max(range(len(dense)), key=lambda i: dense[i][2])  # begin on a visible point
    dense = dense[start:] + dense[:start]
    pts, exit_at = [], None
    for a, b in zip(dense, dense[1:] + dense[:1], strict=True):
        if a[2] >= 0:
            pts.append(a)
        if (a[2] >= 0) != (b[2] >= 0):
            t = a[2] / (a[2] - b[2])
            cut = tuple(p + (q - p) * t for p, q in zip(a, b, strict=True))
            h = math.hypot(cut[0], cut[1])
            cut = (cut[0] / h, cut[1] / h, 0.0)
            if a[2] >= 0:
                exit_at = cut
                pts.append(cut)
            else:
                pts.extend(rim(exit_at, cut))
                pts.append(cut)
    return "M" + "L".join("{:.1f} {:.1f}".format(*project(v)) for v in pts) + "Z"


def mix(c1, c2, t):
    a = [int(c1[i : i + 2], 16) for i in (1, 3, 5)]
    b = [int(c2[i : i + 2], 16) for i in (1, 3, 5)]
    return "#" + "".join(f"{round(x + (y - x) * t):02x}" for x, y in zip(a, b, strict=True))


light = norm(LIGHT)
faces = []
for centres, k, dark, bright in (
    (PENTS, 5, "#0b5e4a", "#4fb393"),
    (HEXES, 6, "#d5dde6", "#ffffff"),
):
    for c in centres:
        rc = rotate(c, *ANGLES)
        if rc[2] < -0.45:
            continue
        corners = [rotate(v, *ANGLES) for v in face(c, k)]
        shade = max(0.0, min(1.0, 0.25 + 0.85 * dot(rc, light)))
        d = outline(corners)
        if d != "MZ":
            faces.append((rc[2], d, mix(dark, bright, shade)))
faces.sort()

paths = "\n".join(f'        <path d="{d}" fill="{fill}" />' for _, d, fill in faces)

